const mongoose = require("mongoose");

const videoVariantSchema = new mongoose.Schema(
  {
    resolution: {
      type: String,
      enum: ["1080p", "720p", "480p", "original"],
      default: "original"
    },
    url: {
      type: String,
      default: "",
      trim: true,
      maxlength: 2000
    },
    mimeType: {
      type: String,
      default: "video/mp4",
      trim: true
    },
    size: {
      type: Number,
      default: 0
    },
    bitrate: {
      type: Number,
      default: 0
    }
  },
  { _id: false }
);

const subtitleSchema = new mongoose.Schema(
  {
    lang: {
      type: String,
      default: "es-MX",
      trim: true
    },
    label: {
      type: String,
      default: "Español (México)",
      trim: true
    },
    url: {
      type: String,
      default: "",
      trim: true
    },
    autoGenerated: {
      type: Boolean,
      default: true
    },
    approved: {
      type: Boolean,
      default: false
    },
    vttContent: {
      type: String,
      default: "",
      trim: true
    }
  },
  { _id: false }
);

const mediaSchema = new mongoose.Schema(
  {
    url: {
      type: String,
      default: "",
      trim: true,
      maxlength: 2000
    },
    type: {
      type: String,
      enum: ["image", "video", ""],
      default: ""
    },
    mimeType: {
      type: String,
      default: "",
      trim: true
    },
    size: {
      type: Number,
      default: 0
    },
    alt: {
      type: String,
      default: "",
      trim: true,
      maxlength: 500
    },
    focalPoint: {
      x: { type: Number, min: 0, max: 1, default: 0.5 },
      y: { type: Number, min: 0, max: 1, default: 0.5 }
    },
    posterUrl: {
      type: String,
      default: "",
      trim: true,
      maxlength: 2000
    },
    width: {
      type: Number,
      default: 0
    },
    height: {
      type: Number,
      default: 0
    },
    orientation: {
      type: String,
      enum: ["vertical", "horizontal", "square", ""],
      default: ""
    },
    variants: {
      type: [videoVariantSchema],
      default: []
    },
    subtitles: {
      type: [subtitleSchema],
      default: []
    },
    processingStatus: {
      type: String,
      enum: ["pending", "processing", "completed", "failed", "ready"],
      default: "ready"
    },
    duration: {
      type: Number,
      default: 0
    },
    trim: {
      start: { type: Number, default: 0 },
      end: { type: Number, default: 0 },
      muted: { type: Boolean, default: false }
    },
    // ---------- Música del estudio ----------
    // La pista elegida y su recorte. `trackId` vacío significa que la
    // publicación no lleva música. El archivo vive en /uploads/music/.
    music: {
      trackId: { type: String, default: "", trim: true, maxlength: 64 },
      titulo: { type: String, default: "", trim: true, maxlength: 160 },
      autor: { type: String, default: "", trim: true, maxlength: 160 },
      url: { type: String, default: "", trim: true, maxlength: 2000 },
      tipo: { type: String, enum: ["catalogo", "propia", ""], default: "" },
      inicio: { type: Number, default: 0, min: 0 },
      fin: { type: Number, default: 0, min: 0 },
      volumen: { type: Number, default: 0.8, min: 0, max: 1 },
      fundidoEntrada: { type: Number, default: 0, min: 0 },
      fundidoSalida: { type: Number, default: 0, min: 0 }
    },
    // ---------- Receta de edición del estudio ----------
    // Lo que el usuario ajustó antes de publicar: medida, corte, filtro,
    // tono, texto y la propia música. El archivo original no se toca: la
    // receta es la que manda al reproducir o al procesar.
    edit: {
      version: { type: Number, default: 1, min: 1, max: 10 },
      medida: {
        type: String,
        enum: ["original", "1:1", "4:5", "9:16", "16:9", "3:1", ""],
        default: ""
      },
      corte: {
        inicio: { type: Number, default: 0, min: 0 },
        fin: { type: Number, default: 0, min: 0 },
        silenciar: { type: Boolean, default: false }
      },
      filtro: {
        id: { type: String, default: "", trim: true, maxlength: 40 },
        intensidad: { type: Number, default: 1, min: 0, max: 1 },
        css: { type: String, default: "", trim: true, maxlength: 300 }
      },
      ajustes: {
        brillo: { type: Number, default: 1, min: 0.5, max: 1.5 },
        contraste: { type: Number, default: 1, min: 0.5, max: 1.5 },
        saturacion: { type: Number, default: 1, min: 0, max: 2 },
        calidez: { type: Number, default: 0, min: -0.3, max: 0.3 },
        exposicion: { type: Number, default: 0, min: -0.4, max: 0.4 },
        desenfoque: { type: Number, default: 0, min: 0, max: 4 },
        vineta: { type: Number, default: 0, min: 0, max: 1 },
        grano: { type: Number, default: 0, min: 0, max: 1 }
      },
      texto: {
        contenido: { type: String, default: "", trim: true, maxlength: 140 },
        posicion: { type: String, enum: ["arriba", "centro", "abajo", ""], default: "" },
        tamano: { type: Number, default: 1, min: 0.6, max: 2 },
        color: { type: String, default: "#ffffff", trim: true, maxlength: 24 },
        fondo: { type: Boolean, default: true }
      },
      // Línea de tiempo: los clips en orden, cada uno con su tramo, su
      // velocidad (0.25x a 4x, que es donde vive la cámara lenta) y la
      // transición con la toma anterior. Solo se llena cuando la pieza lleva
      // más de una toma.
      clips: {
        type: [
          new mongoose.Schema(
            {
              url: { type: String, default: "", trim: true, maxlength: 2000 },
              tipo: { type: String, enum: ["video", "image"], default: "video" },
              duracion: { type: Number, default: 0, min: 0 },
              inicio: { type: Number, default: 0, min: 0 },
              fin: { type: Number, default: 0, min: 0 },
              velocidad: { type: Number, default: 1, min: 0.25, max: 4 },
              transicion: {
                tipo: {
                  type: String,
                  enum: ["corte", "fundido", "negro", "blanco", "barrido", "acercar"],
                  default: "corte"
                },
                duracion: { type: Number, default: 0, min: 0, max: 2 }
              }
            },
            { _id: false }
          )
        ],
        default: []
      },
      duracionTotal: { type: Number, default: 0, min: 0 },
      // Voz en off: una toma de voz sobre la pieza, con su volumen, su punto
      // de entrada y sus fundidos. Vive con la receta, no con el media,
      // porque es parte de la edición.
      voz: {
        voiceId: { type: String, default: "", trim: true, maxlength: 60 },
        nombre: { type: String, default: "", trim: true, maxlength: 160 },
        url: { type: String, default: "", trim: true, maxlength: 2000 },
        tipo: { type: String, enum: ["propia", "catalogo", ""], default: "" },
        inicio: { type: Number, default: 0, min: 0 },
        fin: { type: Number, default: 0, min: 0 },
        volumen: { type: Number, default: 1, min: 0, max: 1 },
        fundidoEntrada: { type: Number, default: 0, min: 0 },
        fundidoSalida: { type: Number, default: 0, min: 0 }
      }
    }
  },
  { _id: false }
);


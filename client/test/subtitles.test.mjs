import test from "node:test";
import assert from "node:assert/strict";

import {
  marcaDeTiempo,
  segundosDeMarca,
  escaparVtt,
  lineasDeSubtitulo,
  construirVtt,
  duracionEstimada,
  pistaDeSubtitulos
} from "../src/lib/subtitles.js";

test("marcaDeTiempo usa el formato de WebVTT", () => {
  assert.equal(marcaDeTiempo(0), "00:00:00.000");
  assert.equal(marcaDeTiempo(1.5), "00:00:01.500");
  assert.equal(marcaDeTiempo(65), "00:01:05.000");
  assert.equal(marcaDeTiempo(3725.25), "01:02:05.250");
  assert.equal(marcaDeTiempo(-3), "00:00:00.000");
  assert.equal(marcaDeTiempo(59.9999), "00:01:00.000");
});

test("segundosDeMarca acepta las formas habituales y rechaza basura", () => {
  assert.equal(segundosDeMarca("12"), 12);
  assert.equal(segundosDeMarca("1:05"), 65);
  assert.equal(segundosDeMarca("01:02:03"), 3723);
  assert.equal(segundosDeMarca("00:12.500"), 12.5);
  assert.equal(segundosDeMarca(7), 7);
  assert.equal(segundosDeMarca(""), null);
  assert.equal(segundosDeMarca("uno"), null);
  assert.equal(segundosDeMarca("1:2:3:4"), null);
});

test("escaparVtt neutraliza las etiquetas", () => {
  assert.equal(escaparVtt("a < b > c & d"), "a &lt; b &gt; c &amp; d");
});

test("una línea del autor es un subtítulo", () => {
  assert.deepEqual(lineasDeSubtitulo("Hola\nAdiós"), ["Hola", "Adiós"]);
  assert.deepEqual(lineasDeSubtitulo("  \n\nHola\n  "), ["Hola"]);
});

test("parte las líneas que no caben en pantalla", () => {
  const largo = "palabra ".repeat(30).trim(); // 239 caracteres
  const lineas = lineasDeSubtitulo(largo, 90);
  assert.ok(lineas.length >= 3);
  for (const linea of lineas) assert.ok(linea.length <= 90, linea);
  assert.equal(lineas.join(" "), largo);
});

test("sin tiempos reparte la duración y termina en el final del video", () => {
  const vtt = construirVtt(["Uno", "Dos"], 10);
  assert.ok(vtt.startsWith("WEBVTT\n\n"));
  assert.match(vtt, /1\n00:00:00\.000 --> /);
  // La última línea cierra exactamente en la duración.
  assert.match(vtt, /--> 00:00:10\.000/);
});

test("respeta los tiempos explícitos", () => {
  const vtt = construirVtt([{ texto: "Uno", inicio: 1, fin: 3 }, { texto: "Dos", inicio: 3, fin: 6 }], 10);
  assert.match(vtt, /00:00:01\.000 --> 00:00:03\.000\nUno/);
  assert.match(vtt, /00:00:03\.000 --> 00:00:06\.000\nDos/);
});

test("nunca deja un final anterior al inicio", () => {
  const vtt = construirVtt([{ texto: "Uno", inicio: 5, fin: 2 }], 10);
  const linea = vtt.split("\n").find((tramo) => tramo.includes("-->"));
  const [desde, hasta] = linea.split(" --> ");
  assert.ok(segundosDeMarca(hasta) > segundosDeMarca(desde));
});

test("sin texto no hay pista", () => {
  assert.equal(construirVtt([], 10), "");
  assert.equal(construirVtt(["   "], 10), "");
});

test("duracionEstimada usa el ritmo de lectura", () => {
  assert.equal(duracionEstimada(""), 0);
  assert.ok(duracionEstimada("x".repeat(28)) > 1.9);
});

test("pistaDeSubtitulos sale aprobada y no autogenerada", () => {
  const pista = pistaDeSubtitulos({ texto: "Hola mundo", duracion: 5 });
  assert.equal(pista.approved, true);
  assert.equal(pista.autoGenerated, false);
  assert.equal(pista.lang, "es-MX");
  assert.ok(pista.vttContent.startsWith("WEBVTT"));
  assert.equal(pistaDeSubtitulos({ texto: "  ", duracion: 5 }), null);
});

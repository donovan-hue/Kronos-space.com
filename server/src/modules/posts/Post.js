const pollSchema = new mongoose.Schema(
  {
    question: {
      type: String,
      required: true,
      trim: true,
      maxlength: 200
    },
    options: {
      type: [pollOptionSchema],
      required: true,
      validate: {
        validator(items) {
          return Array.isArray(items) && items.length >= 2 && items.length <= 6;
        },
        message: "La encuesta debe tener entre 2 y 6 opciones"
      }
    },
    votes: {
      type: [pollVoteSchema],
      default: []
    },
    closesAt: {
      type: Date,
      default: null
    }
  },
  { _id: false }
);

